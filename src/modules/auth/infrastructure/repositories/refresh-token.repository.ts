import { Injectable } from '@nestjs/common';
import { PrismaService } from '@/infrastructure/database/prisma/prisma.service';
import { IRefreshTokenRepository } from '@/modules/auth/domain/repositories/refresh-token.repository';
import { RefreshToken } from '@/modules/auth/domain/aggregates/refresh-token.aggregate';
import { RefreshTokenMapper } from '../mappers/refresh-token.mapper';

@Injectable()
export class PrismaRefreshTokenRepository implements IRefreshTokenRepository {
  constructor(private readonly prisma: PrismaService) {}

  async create(refreshToken: RefreshToken): Promise<void> {
    const data = RefreshTokenMapper.toPersistence(refreshToken);
    await this.prisma.refreshToken.create({
      data: {
        ...data,
        // Ensure we don't pass fields that might be autogenerated or handled differently if needed
        // But mapper returns full object. Prisma create 'data' usually accepts optional for nullables
      },
    });
  }

  async findByJti(jti: string): Promise<RefreshToken | null> {
    const token = await this.prisma.refreshToken.findUnique({
      where: { jti },
    });

    if (!token) return null;

    return RefreshTokenMapper.toDomain(token);
  }

  async save(refreshToken: RefreshToken): Promise<void> {
    const data = RefreshTokenMapper.toPersistence(refreshToken);
    await this.prisma.refreshToken.update({
      where: { id: refreshToken.id },
      data: {
        revoked_at: data.revoked_at,
        updated_at: new Date(),
        // other fields if needed
      },
    });
  }

  async revoke(jti: string): Promise<void> {
    await this.prisma.refreshToken.update({
      where: { jti },
      data: { revoked_at: new Date() },
    });
  }

  async revokeAllForUser(userId: string): Promise<void> {
    await this.prisma.refreshToken.updateMany({
      where: {
        user_id: userId,
        revoked_at: null,
      },
      data: { revoked_at: new Date() },
    });
  }

  async revokeAllForDevice(userId: string, deviceId: string): Promise<void> {
    await this.prisma.refreshToken.updateMany({
      where: {
        user_id: userId,
        device_id: deviceId,
        revoked_at: null,
      },
      data: { revoked_at: new Date() },
    });
  }

  async deleteExpired(): Promise<number> {
    const result = await this.prisma.refreshToken.deleteMany({
      where: {
        expires_at: { lt: new Date() },
      },
    });
    return result.count;
  }
}
