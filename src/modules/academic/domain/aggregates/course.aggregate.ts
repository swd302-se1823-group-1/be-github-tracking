import { AggregateRoot } from '@nestjs/cqrs';
import { generateId } from '@/shared/utils/uuid';

type Mutable<T> = {
  -readonly [P in keyof T]: T[P];
};

export class CourseAggregate extends AggregateRoot {
  private constructor(
    public readonly id: string,
    public readonly code: string,
    public readonly name: string,
    public readonly deletedAt: Date | null,
    public readonly deletedBy: string | null,
    public readonly createdBy: string | null,
    public readonly updatedBy: string | null,
    public readonly createdAt: Date,
    public readonly updatedAt: Date,
  ) {
    super();
  }

  delete(deletedBy: string): void {
    (this as Mutable<CourseAggregate>).deletedAt = new Date();
    (this as Mutable<CourseAggregate>).deletedBy = deletedBy;
    (this as Mutable<CourseAggregate>).updatedAt = new Date();
    (this as Mutable<CourseAggregate>).updatedBy = deletedBy;
  }

  static create(
    code: string,
    name: string,
    createdBy?: string,
  ): CourseAggregate {
    return new CourseAggregate(
      generateId(), // ID generated by App (UUID v7)
      code,
      name,
      null,
      null,
      createdBy || null,
      createdBy || null,
      new Date(),
      new Date(),
    );
  }

  static reconstitute(
    id: string,
    code: string,
    name: string,
    deletedAt: Date | null,
    deletedBy: string | null,
    createdBy: string | null,
    updatedBy: string | null,
    createdAt: Date,
    updatedAt: Date,
  ): CourseAggregate {
    return new CourseAggregate(
      id,
      code,
      name,
      deletedAt,
      deletedBy,
      createdBy,
      updatedBy,
      createdAt,
      updatedAt,
    );
  }
}
