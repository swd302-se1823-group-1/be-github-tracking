import { AggregateRoot } from '@nestjs/cqrs';
import { generateId } from '@/shared/utils/uuid';

type Mutable<T> = {
  -readonly [P in keyof T]: T[P];
};

export class ClassAggregate extends AggregateRoot {
  private constructor(
    public readonly id: string,
    public readonly semesterId: bigint,
    public readonly enrollPassword: string,
    public readonly lecturerId: string,
    public readonly courseId: string,
    public readonly classCode: string,
    public readonly className: string,
    public readonly description: string | null,
    public readonly deletedAt: Date | null,
    public readonly deletedBy: string | null,
    public readonly createdBy: string | null,
    public readonly updatedBy: string | null,
    public readonly createdAt: Date,
    public readonly updatedAt: Date,
  ) {
    super();
  }

  delete(deletedBy: string): void {
    (this as Mutable<ClassAggregate>).deletedAt = new Date();
    (this as Mutable<ClassAggregate>).deletedBy = deletedBy;
    (this as Mutable<ClassAggregate>).updatedAt = new Date();
    (this as Mutable<ClassAggregate>).updatedBy = deletedBy;
  }

  static create(
    semesterId: bigint,
    enrollPassword: string,
    lecturerId: string,
    courseId: string,
    classCode: string,
    className: string,
    description?: string,
    createdBy?: string,
  ): ClassAggregate {
    return new ClassAggregate(
      generateId(), // ID generated by App (UUID v7)
      semesterId,
      enrollPassword,
      lecturerId,
      courseId,
      classCode,
      className,
      description || null,
      null,
      null,
      createdBy || null,
      createdBy || null,
      new Date(),
      new Date(),
    );
  }

  static reconstitute(
    id: string,
    semesterId: bigint,
    enrollPassword: string,
    lecturerId: string,
    courseId: string,
    classCode: string,
    className: string,
    description: string | null,
    deletedAt: Date | null,
    deletedBy: string | null,
    createdBy: string | null,
    updatedBy: string | null,
    createdAt: Date,
    updatedAt: Date,
  ): ClassAggregate {
    return new ClassAggregate(
      id,
      semesterId,
      enrollPassword,
      lecturerId,
      courseId,
      classCode,
      className,
      description,
      deletedAt,
      deletedBy,
      createdBy,
      updatedBy,
      createdAt,
      updatedAt,
    );
  }
}
